// Native (non-browser) half of Beo's audio-glitch test suite — see
// test-audio-youtube.mjs for the Chrome/WebView half. Installs the bundled
// Beo Diagnostics app (resources/beo-diagnostics.apk) on a throwaway
// device via Beo's real `install_diagnostics_apk` command, taps its "Play
// Music File" button (native Android `MediaPlayer` playing a bundled WAV,
// see diagnostics-app's MainActivity.kt), confirms real audio focus, and
// checks logcat for the same underrun/glitch signatures.
//
// Why this exists as a second script rather than just trusting the YouTube
// one: Chrome/WebView has its own decode and playback path, so a clean
// result there doesn't prove the underlying emulator audio pipeline
// (AudioFlinger → virtio-snd/Intel HDA → QEMU → DirectSound) is actually
// fine — and a glitchy result there doesn't prove the *emulator* is at
// fault either, since Chrome itself could be the source. Running the same
// check against a plain native MediaPlayer, using content that never
// touches a browser at all, tells you which side of that line the problem
// is on: glitches in both point at the emulator's audio pipeline; glitches
// only in the browser point at Chrome.
//
// The played file (diagnostics-app/app/src/main/res/raw/sample_song.wav) is
// synthetic — generated by scripts/generate-sample-song.mjs, not a real
// downloaded track — specifically to avoid any licensing question and stay
// fully reproducible.
//
// Deliberately local-only, not wired into CI — same reasoning as the other
// e2e scripts (real emulator boot).
//
// Usage: node scripts/test-audio-file.mjs [--skip-build]

import { setTimeout as sleep } from "node:timers/promises";
import {
  captureAndAnalyzeLogcat,
  captureDebugState,
  cleanupAvd,
  connectToBeo,
  createAndBootAvd,
  hasAudioFocus,
  makeLogger,
  tapText,
} from "./lib/audio-test-common.mjs";

const skipBuild = process.argv.includes("--skip-build");
const CDP_PORT = 9336; // distinct from test-audio-youtube.mjs's 9335 so both could run concurrently if ever needed
const DEVICE = "audio_file_test";

const { log, fail } = makeLogger("audio-file-test");

async function main() {
  log("waiting for CDP endpoint...");
  const { child, ws, call, adbPath } = await connectToBeo({ skipBuild, cdpPort: CDP_PORT });

  try {
    const serial = await createAndBootAvd({ call, log, device: DEVICE });

    log("installing and launching Beo Diagnostics (real install_diagnostics_apk command)...");
    const installed = await call("install_diagnostics_apk", { name: DEVICE });
    if (!installed.ok) throw new Error(`install_diagnostics_apk failed: ${installed.error}`);
    await sleep(3000);

    log('tapping "Play Music File"...');
    const tapped = await tapText(adbPath, serial, /^play music file$/i);
    if (!tapped) {
      await captureDebugState({ adbPath, serial, log, tag: "audio_file_test" });
      throw new Error('could not find the "Play Music File" button — did the diagnostics app UI change?');
    }
    // Confirmed live (same race already found in test-audio-youtube.mjs): a
    // single fixed sleep here caused a false negative — the tap genuinely
    // started playback (button flipped to "Stop Music File", status text
    // updated), but dumpsys audio hadn't registered the new focus yet at
    // the moment of the single check. Poll instead of trusting one read.
    let playing = false;
    for (let i = 0; i < 4 && !playing; i++) {
      await sleep(1500);
      playing = await hasAudioFocus(adbPath, serial);
    }

    if (!playing) {
      await captureDebugState({ adbPath, serial, log, tag: "audio_file_test" });
      fail("could not confirm real playback (no AudioManager focus held) after tapping Play Music File");
    } else {
      log("  ok — real native playback confirmed (MediaPlayer holds audio focus)");
      // MainActivity loops the sample (MediaPlayer.isLooping = true), so
      // one tap sustains continuous playback for the whole capture window
      // without needing to re-tap when the ~6s clip finishes.
      await captureAndAnalyzeLogcat({ adbPath, serial, log, fail, playSeconds: 45 });
    }

    await cleanupAvd({ call, child, device: DEVICE, adbPath, serial, log });
    ws.close();
  } catch (e) {
    child.kill("SIGKILL");
    throw e;
  }

  if (process.exitCode === 1) {
    console.error("[audio-file-test] one or more checks failed — see above");
  } else {
    log("done.");
  }
}

main().catch((e) => {
  console.error("[audio-file-test] unexpected error:", e);
  process.exitCode = 1;
});
